void solve() {
  ll a,b,x;cin>>a>>b>>x;
  ll ans = abs(a-b);
  ll d=0;
  while(a or b) {
    ans=min(ans,abs(a-b)+d);
    if(a>b)a/=x;
    else b/=x;
    ++d;
  }
  ans=min(ans,d);
  cout<<ans<<'\n';
}


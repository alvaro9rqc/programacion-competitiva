void solve() {
  int n;cin>>n;
  vl arr(n); for(auto& i: arr) cin >> i;  
  ll h = arr[0];
  ll ans = h;
  for (auto i = 1; i < n; i++) {
    if(arr[i]<h) {
      h=arr[i];
      ans+=h;
    } else {
      ans+=h;
    }
  }
  cout<<ans<<'\n';
}

int main() {
  cin.tie(0)->sync_with_stdio(0);
  cin.exceptions(cin.failbit);
  int tt=1;
  cin>>tt;
  while(tt--) {
    solve();
  }
}

